#!/usr/bin/env python3
"""
make_sample_daily.py — generate realistic SYNTHETIC daily health data.

Writes two committed demo files:
    data/sample-daily.json  : plain JSON (for the server / fetch path)
    data/sample-daily.js    : sets window.HUIFAN_SAMPLE_DAILY (file:// path)

This is clearly-labeled fake data so the app shows something when no real
data/daily.json is present, and so anyone cloning the repo can run the demo.
Standard library only. Deterministic (fixed seed) so the demo is stable.
"""

import json
import math
import os
import random
from datetime import date, timedelta

SEED = 42
N_DAYS = 200  # a 30-day baseline + many pairs for CV and insights

# Personal baselines for a plausible young adult. These are the "usual" values
# the synthetic person varies around — NOT medical reference ranges.
HRV_MEAN, HRV_SD = 55.0, 9.0     # ms
RHR_MEAN, RHR_SD = 58.0, 3.0     # bpm
RESP_MEAN, RESP_SD = 15.0, 0.8   # breaths/min
SLEEP_MEAN, SLEEP_SD = 7.4, 0.9  # hours


def clamp(x, lo, hi):
    return max(lo, min(hi, x))


def build(rng):
    """Build N_DAYS of synthetic rows ending today.

    We inject a mild weekly rhythm (slightly worse recovery on a couple of
    'rough' days) and a few missing values, so the baseline and bands show
    variety in the demo.
    """
    rows = []
    today = date.today()
    start = today - timedelta(days=N_DAYS - 1)

    for i in range(N_DAYS):
        d = start + timedelta(days=i)
        # A gentle weekly wobble so some days read low and some high.
        wobble = math.sin(i / 7.0 * 2 * math.pi)

        hrv = rng.gauss(HRV_MEAN + 4 * wobble, HRV_SD)
        rhr = rng.gauss(RHR_MEAN - 1.2 * wobble, RHR_SD)
        resp = rng.gauss(RESP_MEAN - 0.3 * wobble, RESP_SD)
        sleep = rng.gauss(SLEEP_MEAN + 0.4 * wobble, SLEEP_SD)

        row = {
            "date": d.isoformat(),
            "hrv": round(clamp(hrv, 20, 110), 1),
            "rhr": round(clamp(rhr, 45, 80), 1),
            "resp": round(clamp(resp, 11, 20), 1),
            "sleep_h": round(clamp(sleep, 3.5, 10.0), 2),
        }

        # Sprinkle a few realistic gaps (watch not worn, etc.).
        if rng.random() < 0.08:
            row["hrv"] = None
        if rng.random() < 0.05:
            row["resp"] = None
        if rng.random() < 0.05:
            row["sleep_h"] = None

        rows.append(row)

    # Make the most recent day clearly "low recovery" so the demo lands on a
    # yellow/red score with a visible reason: poor sleep + low HRV.
    rows[-1]["hrv"] = 41.0
    rows[-1]["rhr"] = 63.0
    rows[-1]["resp"] = 16.2
    rows[-1]["sleep_h"] = 5.6
    return rows


def main():
    rng = random.Random(SEED)
    rows = build(rng)

    os.makedirs("data", exist_ok=True)

    json_path = os.path.join("data", "sample-daily.json")
    with open(json_path, "w") as f:
        json.dump(rows, f, indent=2)
        f.write("\n")

    js_path = os.path.join("data", "sample-daily.js")
    with open(js_path, "w") as f:
        f.write("// SYNTHETIC sample data for the Huifan demo. Not real health data.\n")
        f.write("// Generated by scripts/make_sample_daily.py (deterministic seed).\n")
        f.write("window.HUIFAN_SAMPLE_DAILY = ")
        json.dump(rows, f, indent=2)
        f.write(";\n")

    print(f"Wrote {len(rows)} synthetic days to {json_path} and {js_path}")


if __name__ == "__main__":
    main()
